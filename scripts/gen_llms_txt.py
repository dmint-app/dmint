#!/usr/bin/env python3
"""deterministically generate docs/public/llms-full.txt, docs/public/llms.txt, and docs/public/sitemap.xml from docs/docs.json."""

from __future__ import annotations

import json
import re
from pathlib import Path


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    docs_dir = repo_root / "docs"
    nav = json.loads((docs_dir / "docs.json").read_text(encoding="utf-8"))

    sitemap_lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    llms_full_chunks = [
        "<!-- generated by scripts/gen_llms_txt.py; do not edit -->",
        "# Dmint — Complete Documentation (Full Text Corpus)",
        "> Dmint is a deterministic security authorization and enforcement engine for AI-agent tool calls.",
        "> Website: https://dmint.app | Docs: https://docs.dmint.app",
        "",
    ]
    llms_index_sections = []

    for grp in nav["navigation"]["groups"]:
        group_name = grp["group"]
        section_links = [f"### {group_name}"]
        for page_slug in grp["pages"]:
            mdx_path = docs_dir / f"{page_slug}.mdx"
            raw = mdx_path.read_text(encoding="utf-8")
            title = page_slug
            desc = ""
            body = raw
            m = re.match(r"^---\n(.*?)\n---\n+(.*)", raw, re.DOTALL)
            if m:
                fm, body = m.group(1), m.group(2)
                tm = re.search(r"^title:\s*\"(.*?)\"", fm, re.MULTILINE)
                dm = re.search(r"^description:\s*\"(.*?)\"", fm, re.MULTILINE)
                if tm:
                    title = tm.group(1)
                if dm:
                    desc = dm.group(1)

            url = "https://docs.dmint.app/" if page_slug == "index" else f"https://docs.dmint.app/{page_slug}"
            priority = "1.0" if page_slug == "index" else ("0.9" if page_slug == "quickstart" else "0.8")
            freq = "daily" if page_slug == "index" else "weekly"
            sitemap_lines.extend(
                [
                    "  <url>",
                    f"    <loc>{url}</loc>",
                    f"    <changefreq>{freq}</changefreq>",
                    f"    <priority>{priority}</priority>",
                    "  </url>",
                ]
            )

            llms_full_chunks.extend(
                [
                    "",
                    "=" * 80,
                    f"DOCUMENT: {title}",
                    f"URL: {url}",
                    f"SECTION: {group_name}",
                    f"SUMMARY: {desc}",
                    "=" * 80,
                    "",
                    body.strip(),
                    "",
                ]
            )
            section_links.append(f"- [{title}]({url}): {desc}")
        llms_index_sections.append("\n".join(section_links))

    sitemap_lines.append("</urlset>\n")
    (docs_dir / "public" / "sitemap.xml").write_text("\n".join(sitemap_lines), encoding="utf-8")
    (docs_dir / "public" / "llms-full.txt").write_text("\n".join(llms_full_chunks), encoding="utf-8")

    p_llms = docs_dir / "public" / "llms.txt"
    llms_text = p_llms.read_text(encoding="utf-8")
    if not llms_text.startswith("<!-- generated by scripts/gen_llms_txt.py"):
        llms_text = "<!-- generated by scripts/gen_llms_txt.py; do not edit -->\n" + llms_text
    idx_marker = "## Complete Documentation Index"
    prefix = llms_text.split(idx_marker)[0]
    new_llms_text = (
        prefix
        + "## Complete Documentation Index\n\n"
        + f"For the full, single-file plain-text corpus of all {sum(len(g['pages']) for g in nav['navigation']['groups'])} documentation pages, read [llms-full.txt](https://docs.dmint.app/llms-full.txt).\n\n"
        + "\n\n".join(llms_index_sections)
        + "\n"
    )
    p_llms.write_text(new_llms_text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
