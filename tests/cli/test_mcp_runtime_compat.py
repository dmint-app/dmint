class EnforcementGateRuntimeTests(unittest.IsolatedAsyncioTestCase):
    """Req 5 & 6: Start a real EnforcementGate and exercise authorization decisions."""

    def _make_gate(
        self,
        integration_id: str,
        tool_names: list[str],
        effect: str = "allow",
    ) -> tuple[EnforcementGate, MagicMock]:
        cfg = MCPIntegrationConfig(
            integration_id=integration_id,
            command="npx",
            args=[],
            tool_bindings=[_make_tool_binding(t, integration_id) for t in tool_names],
            default_discovery=DiscoveryMode.EXPOSED,
        )
        policy = _policy_for_tools(integration_id, tool_names, effect=effect)
        client = _make_downstream_client(tool_names)
        gate = EnforcementGate(client, cfg, policy=policy, agent_id="test-agent")
        return gate, client

    async def test_startup_succeeds_single_integration(self):
        """Req 6a: Startup (EnforcementGate construction) succeeds for one integration."""
        gate, _ = self._make_gate("postgres", ["query"])
        self.assertIsNotNone(gate)
        self.assertIsInstance(gate, EnforcementGate)

    async def test_integrations_load_with_real_config(self):
        """Req 6b: Integration config and tool bindings are loaded into the gate."""
        gate, _ = self._make_gate("postgres", ["query", "schema"])
        self.assertIsNotNone(gate.mapper)
        self.assertIn("query", gate.mapper._config.tool_bindings)
        self.assertIn("schema", gate.mapper._config.tool_bindings)

    async def test_tool_bindings_load(self):
        """Req 6c: Tool bindings are available from the gate's config."""
        gate, _ = self._make_gate("postgres", ["query"])
        binding = gate.mapper._config.tool_bindings["query"]
        self.assertEqual(binding.tool_name, "query")
        self.assertEqual(binding.capability, "mcp.postgres.query")

    async def test_list_tools_matches_config_discovery(self):
        """Req 6d: list_tools returns tools matching the binding discovery config."""
        gate, client = self._make_gate("postgres", ["query", "schema"])
        # Mock downstream list_tools to return the bound tools
        result = await gate.list_tools()
        # All tools are EXPOSED by default in _make_tool_binding
        tool_names = {t.name for t in result.tools}
        self.assertIn("query", tool_names)
        self.assertIn("schema", tool_names)

    async def test_authorized_tool_call_succeeds(self):
        """Req 6e: Authorized tool call (ALLOW policy) succeeds and calls downstream."""
        gate, client = self._make_gate("postgres", ["query"])
        result = await gate.route_call(
            integration_id="postgres",
            tool_name="query",
            arguments={"sql": "SELECT 1"},
        )
        self.assertIsInstance(result, mcp_types.CallToolResult)
        self.assertFalse(result.is_error)
        client.call_tool.assert_called_once()

    async def test_unauthorized_tool_call_is_denied(self):
        """Req 6f: Denied tool call (DENY policy) raises AuthorizationError before downstream."""
        gate, client = self._make_gate("postgres", ["query"], effect="deny")
        with self.assertRaises(AuthorizationError) as ctx:
            await gate.route_call(
                integration_id="postgres",
                tool_name="query",
                arguments={},
            )
        self.assertIn("denied", str(ctx.exception).lower())
        # Downstream must NOT have been called
        client.call_tool.assert_not_called()

    async def test_unknown_tool_denied_before_downstream(self):
        """Fail-closed: unknown tool → MCPMappingError before downstream execution."""
        gate, client = self._make_gate("postgres", ["query"])
        with self.assertRaises(MCPMappingError):
            await gate.route_call(
                integration_id="postgres",
                tool_name="nonexistent_tool",
                arguments={},
            )
        client.call_tool.assert_not_called()

    async def test_empty_policy_denies_all_tools(self):
        """Req 3 (default deny): empty policy denies all tool calls."""
        cfg = MCPIntegrationConfig(
            integration_id="postgres",
            command="npx",
            args=[],
            tool_bindings=[_make_tool_binding("query", "postgres")],
        )
        policy = Policy.from_mapping({"rules": []})  # empty policy → deny-all
        client = _make_downstream_client(["query"])
        gate = EnforcementGate(client, cfg, policy=policy, agent_id="test-agent")
        with self.assertRaises(AuthorizationError):
            await gate.route_call(
                integration_id="postgres",
                tool_name="query",
                arguments={},
            )
        client.call_tool.assert_not_called()


