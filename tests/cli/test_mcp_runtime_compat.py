class RealSubprocessRuntimeTests(unittest.IsolatedAsyncioTestCase):
    """Req 5 & 6: Start a real test runtime connecting to an actual downstream MCP process."""

    async def test_real_downstream_mcp_subprocess_enforcement(self):
        mock_server_script = str(Path(__file__).resolve().parent.parent / "mcp" / "mock_server.py")

        # 1. Build integration configuration
        integ_dict = _integ_dict(
            "mock-server",
            sys.executable,
            args=[mock_server_script],
            tool_names=["echo", "delete_database"],
        )
        config = _build_protection_config("policy.json", [integ_dict])
        validate_mcp_protection_config(config)

        # 2. Parse into real MCPIntegrationConfig
        mcp_cfg = _cfg_from_integ_dict(integ_dict)

        # 3. Build real Policy allowing only 'echo'
        policy = Policy.from_mapping(
            {
                "rules": [
                    {
                        "effect": "allow",
                        "tool": "mcp",
                        "action": "mock-server.echo",
                        "resource": "*",
                    },
                ]
            }
        )

        # 4. Start real DmintMCPProxy connected to real downstream subprocess
        proxy = DmintMCPProxy(mcp_cfg, policy=policy)
        try:
            await proxy.connect()

            # Startup succeeds and gate is ready
            self.assertIsNotNone(proxy.gate)

            # Discovery matches config
            tools_result = await proxy.list_tools()
            tool_names = {t.name for t in tools_result.tools}
            self.assertIn("echo", tool_names)
            self.assertIn("delete_database", tool_names)

            # Authorized tool call succeeds against the real downstream server
            auth_result = await proxy.gate.route_call(
                integration_id="mock-server",
                tool_name="echo",
                arguments={"message": "hello from dmint-cli test"},
            )
            self.assertFalse(auth_result.is_error)
            self.assertEqual(auth_result.content[0].text, "echo: hello from dmint-cli test")

            # Unauthorized tool call is denied by Dmint policy before downstream execution
            with self.assertRaises(AuthorizationError):
                await proxy.gate.route_call(
                    integration_id="mock-server",
                    tool_name="delete_database",
                    arguments={"target": "prod-db"},
                )
        finally:
            await proxy.disconnect()


