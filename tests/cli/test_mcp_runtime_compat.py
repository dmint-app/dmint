class CapabilityTranslationCompatibilityTests(unittest.TestCase):
    """Req 6: Verify capability → ToolRequest translation through the real mapper."""

    def _make_mapper(self, integration_id: str, tool_names: list[str]) -> MCPRequestMapper:
        cfg = MCPIntegrationConfig(
            integration_id=integration_id,
            command="npx",
            args=[],
            tool_bindings=[_make_tool_binding(t, integration_id) for t in tool_names],
        )
        return MCPRequestMapper(cfg, agent_id="test-agent", context=TrustedContext({}))

    def test_canonical_capability_produces_correct_tool_and_action(self):
        """mcp.<integ>.<tool> binding → tool='mcp', action='<integ>.<tool>' in ToolRequest."""
        mapper = self._make_mapper("postgres", ["query"])
        mapped = mapper.map(tool_name="query", arguments={})
        self.assertEqual(mapped.tool_request.tool, "mcp")
        self.assertEqual(mapped.tool_request.action, "postgres.query")
        self.assertEqual(mapped.capability, "mcp.postgres.query")

    def test_multiple_tools_each_translate_correctly(self):
        """Each tool in an integration maps to a distinct tool+action pair."""
        mapper = self._make_mapper("postgres", ["query", "schema", "delete"])
        for tool_name in ["query", "schema", "delete"]:
            mapped = mapper.map(tool_name=tool_name, arguments={})
            self.assertEqual(mapped.tool_request.tool, "mcp")
            self.assertEqual(mapped.tool_request.action, f"postgres.{tool_name}")

    def test_unbound_tool_raises_mcpmappingerror(self):
        """Req 6 fail-closed: a tool not in bindings raises MCPMappingError."""
        mapper = self._make_mapper("postgres", ["query"])
        with self.assertRaises(MCPMappingError):
            mapper.map(tool_name="unknown_tool", arguments={})

    def test_policy_must_use_mcp_form_to_authorize(self):
        """Policy rule must match tool='mcp', action='<integ>.<tool>' to authorize."""
        mapper = self._make_mapper("postgres", ["query"])
        mapped = mapper.map(tool_name="query", arguments={})

        # Wrong form — tool name as integration_id, action as tool_name
        policy_wrong = Policy.from_mapping(
            {"rules": [{"effect": "allow", "tool": "postgres", "action": "query", "resource": "*"}]}
        )
        self.assertEqual(policy_wrong.evaluate(mapped.tool_request), Decision.DENY)

        # Correct runtime-compatible form
        policy_correct = Policy.from_mapping(
            {"rules": [{"effect": "allow", "tool": "mcp", "action": "postgres.query", "resource": "*"}]}
        )
        self.assertEqual(policy_correct.evaluate(mapped.tool_request), Decision.ALLOW)

    def test_two_integrations_do_not_collide_in_policy(self):
        """Same tool name on two different integrations maps to distinct action values."""
        mapper_a = self._make_mapper("alpha", ["read"])
        mapper_b = self._make_mapper("beta", ["read"])
        mapped_a = mapper_a.map(tool_name="read", arguments={})
        mapped_b = mapper_b.map(tool_name="read", arguments={})
        # Both have tool='mcp' but distinct actions
        self.assertEqual(mapped_a.tool_request.tool, "mcp")
        self.assertEqual(mapped_a.tool_request.action, "alpha.read")
        self.assertEqual(mapped_b.tool_request.tool, "mcp")
        self.assertEqual(mapped_b.tool_request.action, "beta.read")
        # A policy allowing alpha.read must NOT authorize beta.read
        policy = Policy.from_mapping(
            {"rules": [{"effect": "allow", "tool": "mcp", "action": "alpha.read", "resource": "*"}]}
        )
        self.assertEqual(policy.evaluate(mapped_a.tool_request), Decision.ALLOW)
        self.assertEqual(policy.evaluate(mapped_b.tool_request), Decision.DENY)


