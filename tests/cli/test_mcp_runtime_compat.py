def _make_tool_binding(tool_name: str, integration_id: str) -> MCPToolBinding:
    """Build the MCPToolBinding exactly as validate_mcp_protection_config does."""
    capability = f"mcp.{integration_id}.{tool_name}"
    return MCPToolBinding(
        tool_name=tool_name,
        capability=capability,
        discovery=DiscoveryMode.EXPOSED,
    )


def _build_protection_config(
    policy_file: str,
    integrations: list[dict[str, Any]],
) -> dict[str, Any]:
    """Build an mcp_protection.json dict in the exact format dmint-cli generates."""
    return {
        "policy_file": policy_file,
        "integrations": integrations,
    }


def _integ_dict(
    integration_id: str,
    command: str,
    args: list[str] | None = None,
    transport: str = "stdio",
    tool_names: list[str] | None = None,
) -> dict[str, Any]:
    """Build an integration entry in the format MCPIntegration.to_dict() produces."""
    bindings: dict[str, Any] = {}
    for name in tool_names or []:
        bindings[name] = {
            "tool_name": name,
            "capability": f"mcp.{integration_id}.{name}",
            "discovery": "exposed",
        }
    return {
        "integration_id": integration_id,
        "transport": transport,
        "connection": {"command": command, "args": args or []},
        "tool_bindings": bindings,
    }


def _cfg_from_integ_dict(integ: dict[str, Any]) -> MCPIntegrationConfig:
    """Parse one integration dict entry into a real MCPIntegrationConfig.

    This is the exact same logic that the production runtime loader would use;
    it calls MCPIntegrationConfig directly — no fake parser.
    """
    integration_id = integ["integration_id"]
    transport_str = integ.get("transport", "stdio")
    conn = integ.get("connection", {})
    raw_bindings = integ.get("tool_bindings", {})

    tool_bindings: list[MCPToolBinding] = []
    if isinstance(raw_bindings, dict):
        for tool_name, spec in raw_bindings.items():
            if isinstance(spec, dict):
                tool_bindings.append(
                    MCPToolBinding(
                        tool_name=spec.get("tool_name", tool_name),
                        capability=spec.get("capability", f"mcp.{integration_id}.{tool_name}"),
                        discovery=spec.get("discovery", "exposed"),
                    )
                )
    elif isinstance(raw_bindings, list):
        for spec in raw_bindings:
            if isinstance(spec, dict) and "tool_name" in spec and "capability" in spec:
                tool_bindings.append(
                    MCPToolBinding(
                        tool_name=spec["tool_name"],
                        capability=spec["capability"],
                        discovery=spec.get("discovery", "exposed"),
                    )
                )

    return MCPIntegrationConfig(
        integration_id=integration_id,
        command=conn.get("command", ""),
        args=conn.get("args", []),
        transport_type=transport_str,
        tool_bindings=tool_bindings,
        default_discovery=DiscoveryMode.HIDDEN,
    )


def _policy_for_tools(
    integration_id: str,
    tool_names: list[str],
    effect: str = "allow",
) -> Policy:
    """Build a runtime-compatible policy for the given integration tools.

    The mapper splits capability 'mcp.<integ>.<tool>' as tool='mcp',
    action='<integ>.<tool>', so policy rules must use that exact form.
    """
    rules = []
    for tool_name in tool_names:
        rules.append(
            {
                "effect": effect,
                "tool": "mcp",
                "action": f"{integration_id}.{tool_name}",
                "resource": "*",
            }
        )
    return Policy.from_mapping({"rules": rules})


def _make_downstream_client(tool_names: list[str]) -> MagicMock:
    """Build a mock DownstreamMCPClient that returns the given tool names."""
    client = MagicMock()
    client.__class__.__name__ = "DownstreamMCPClient"

    # list_tools returns real mcp.types.Tool objects
    tools = [
        mcp_types.Tool(
            name=name,
            description=f"tool {name}",
            inputSchema={"type": "object", "properties": {}},
        )
        for name in tool_names
    ]
    client.list_tools = AsyncMock(return_value=tools)

    def _call_tool_side_effect(name, arguments=None):
        return mcp_types.CallToolResult(content=[mcp_types.TextContent(type="text", text=f"result:{name}")])

    client.call_tool = AsyncMock(side_effect=_call_tool_side_effect)

    # Make isinstance(client, DownstreamMCPClient) pass
    from dmint.mcp.client import DownstreamMCPClient

    client.__class__ = DownstreamMCPClient
    return client


