class MultipleIntegrationsRuntimeTests(unittest.IsolatedAsyncioTestCase):
    """Req 10: Test multiple integrations each with their own gate and policy."""

    async def test_two_integrations_with_separate_gates(self):
        """Each integration has its own gate; policies are isolated."""

        def _gate(iid, tools, effect="allow"):
            cfg = MCPIntegrationConfig(
                integration_id=iid,
                command="npx",
                args=[],
                tool_bindings=[_make_tool_binding(t, iid) for t in tools],
            )
            policy = _policy_for_tools(iid, tools, effect=effect)
            client = _make_downstream_client(tools)
            return EnforcementGate(client, cfg, policy=policy, agent_id="test-agent"), client

        gate_alpha, client_alpha = _gate("alpha", ["read"])
        gate_beta, client_beta = _gate("beta", ["write"])

        result_alpha = await gate_alpha.route_call(integration_id="alpha", tool_name="read", arguments={})
        self.assertFalse(result_alpha.is_error)
        client_alpha.call_tool.assert_called_once()

        result_beta = await gate_beta.route_call(integration_id="beta", tool_name="write", arguments={})
        self.assertFalse(result_beta.is_error)
        client_beta.call_tool.assert_called_once()

    async def test_alpha_policy_cannot_authorize_beta_tool(self):
        """Policy for integration alpha must not authorize beta's tools (no cross-contamination)."""
        cfg_beta = MCPIntegrationConfig(
            integration_id="beta",
            command="npx",
            args=[],
            tool_bindings=[_make_tool_binding("write", "beta")],
        )
        # Use alpha's policy on beta's gate
        alpha_policy = _policy_for_tools("alpha", ["write"])  # tool='mcp', action='alpha.write'
        client_beta = _make_downstream_client(["write"])
        gate_beta = EnforcementGate(client_beta, cfg_beta, policy=alpha_policy, agent_id="test-agent")
        # beta's mapper will produce action='beta.write', alpha's policy covers action='alpha.write'
        with self.assertRaises(AuthorizationError):
            await gate_beta.route_call(integration_id="beta", tool_name="write", arguments={})
        client_beta.call_tool.assert_not_called()

    async def test_same_tool_name_on_two_servers_is_isolated(self):
        """Req 9 (single) & Req 10 (multiple): Same tool name on two servers → distinct capabilities."""
        cfg_a = MCPIntegrationConfig(
            integration_id="serverA",
            command="npx",
            args=[],
            tool_bindings=[_make_tool_binding("read", "serverA")],
        )
        cfg_b = MCPIntegrationConfig(
            integration_id="serverB",
            command="npx",
            args=[],
            tool_bindings=[_make_tool_binding("read", "serverB")],
        )
        # Each server gets a policy that only allows its own read tool
        policy_a = _policy_for_tools("serverA", ["read"])
        policy_b = _policy_for_tools("serverB", ["read"])

        client_a = _make_downstream_client(["read"])
        client_b = _make_downstream_client(["read"])

        gate_a = EnforcementGate(client_a, cfg_a, policy=policy_a, agent_id="agent")
        gate_b = EnforcementGate(client_b, cfg_b, policy=policy_b, agent_id="agent")

        result_a = await gate_a.route_call(integration_id="serverA", tool_name="read", arguments={})
        self.assertFalse(result_a.is_error)

        result_b = await gate_b.route_call(integration_id="serverB", tool_name="read", arguments={})
        self.assertFalse(result_b.is_error)

        # Cross-contamination: serverA's policy must NOT authorize serverB's tool
        gate_cross = EnforcementGate(client_b, cfg_b, policy=policy_a, agent_id="agent")
        with self.assertRaises(AuthorizationError):
            await gate_cross.route_call(integration_id="serverB", tool_name="read", arguments={})


