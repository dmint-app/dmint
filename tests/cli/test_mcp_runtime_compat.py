class ProtectionConfigParsingTests(unittest.TestCase):
    """Req 4 & 8: Feed generated artifact into the actual dmint-mcp runtime parser."""

    def test_single_integration_parses_to_real_mcpintegrationconfig(self):
        """The generated config round-trips through the real MCPIntegrationConfig constructor."""
        integ = _integ_dict(
            "postgres", "npx", ["-y", "@modelcontextprotocol/server-postgres"], tool_names=["query", "schema"]
        )
        cfg = _cfg_from_integ_dict(integ)
        self.assertIsInstance(cfg, MCPIntegrationConfig)
        self.assertEqual(cfg.integration_id, "postgres")
        self.assertEqual(cfg.transport_type, MCPTransportType.STDIO)
        self.assertEqual(cfg.command, "npx")
        self.assertEqual(cfg.args, ("-y", "@modelcontextprotocol/server-postgres"))

    def test_tool_bindings_load_with_canonical_capability_form(self):
        """Each tool binding carries the mcp.<integration>.<tool> canonical capability."""
        integ = _integ_dict("postgres", "npx", tool_names=["query", "schema"])
        cfg = _cfg_from_integ_dict(integ)
        self.assertIn("query", cfg.tool_bindings)
        self.assertIn("schema", cfg.tool_bindings)
        self.assertEqual(cfg.tool_bindings["query"].capability, "mcp.postgres.query")
        self.assertEqual(cfg.tool_bindings["schema"].capability, "mcp.postgres.schema")

    def test_zero_tools_parses_safely(self):
        """Req 11: An integration with no tool bindings must load without error."""
        integ = _integ_dict("empty-server", "npx", tool_names=[])
        cfg = _cfg_from_integ_dict(integ)
        self.assertIsInstance(cfg, MCPIntegrationConfig)
        self.assertEqual(len(cfg.tool_bindings), 0)

    def test_multiple_integrations_each_parse_independently(self):
        """Req 10: Multiple integrations are each independently parsed."""
        integ_a = _integ_dict("alpha", "cmd-a", tool_names=["read"])
        integ_b = _integ_dict("beta", "cmd-b", tool_names=["write"])
        cfg_a = _cfg_from_integ_dict(integ_a)
        cfg_b = _cfg_from_integ_dict(integ_b)
        self.assertEqual(cfg_a.integration_id, "alpha")
        self.assertEqual(cfg_b.integration_id, "beta")
        self.assertIn("read", cfg_a.tool_bindings)
        self.assertIn("write", cfg_b.tool_bindings)
        self.assertNotIn("write", cfg_a.tool_bindings)
        self.assertNotIn("read", cfg_b.tool_bindings)

    def test_unknown_transport_raises_mcpconfigurationerror(self):
        """Req 12: Unknown transport type raises MCPConfigurationError from the real parser."""
        integ = _integ_dict("bad", "npx", transport="grpc", tool_names=["foo"])
        with self.assertRaises(MCPConfigurationError):
            _cfg_from_integ_dict(integ)

    def test_malformed_config_missing_integration_id_fails(self):
        """Req 13: Malformed config with empty integration_id raises from real parser."""
        integ = _integ_dict("", "npx", tool_names=["foo"])
        with self.assertRaises(MCPConfigurationError):
            _cfg_from_integ_dict(integ)

    def test_malformed_config_missing_command_fails(self):
        """Req 13: Malformed config with empty command raises from real parser."""
        integ = {
            "integration_id": "ok",
            "transport": "stdio",
            "connection": {"command": "", "args": []},
            "tool_bindings": {},
        }
        with self.assertRaises(MCPConfigurationError):
            _cfg_from_integ_dict(integ)

    def test_duplicate_integration_ids_detected_by_validator(self):
        """Req 14: validate_mcp_protection_config detects and rejects duplicate integration IDs."""
        from dmint.cli.errors import CLIError

        config = _build_protection_config(
            "policy.json",
            [
                _integ_dict("postgres", "npx", tool_names=["query"]),
                _integ_dict("postgres", "node", tool_names=["read"]),  # duplicate ID
            ],
        )
        with self.assertRaises(CLIError) as ctx:
            validate_mcp_protection_config(config)
        self.assertIn("Duplicate integration ID", str(ctx.exception))


